// Helper to calculate a deterministic 7-day performance growth & usage trend array for Recharts sparklines
export function getModelTrend(model: AiModel): { data: { day: string; value: number }[]; growth: string } {
  // Deterministic seed based on string hash
  let hash = 0;
  for (let i = 0; i < model.id.length; i++) {
    hash = (hash << 5) - hash + model.id.charCodeAt(i);
    hash |= 0;
  }
  const seed = Math.abs(hash) % 100;

  const base = 50 + (seed % 35);
  const days = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];

  const step1 = base + ((seed * 3) % 10);
  const step2 = step1 + ((seed * 7) % 12);
  const step3 = step2 - ((seed * 2) % 6);
  const step4 = step3 + ((seed * 5) % 14);
  const step5 = step4 + ((seed * 4) % 11);
  const step6 = step5 + ((seed * 9) % 15);
  const step7 = step6 + ((seed * 6) % 16) + 5;

  const values = [base, step1, step2, step3, step4, step5, step7];
  const growthVal = (((values[6] - values[0]) / values[0]) * 100).toFixed(1);

  return {
    data: days.map((day, idx) => ({ day, value: values[idx] })),
    growth: `+${growthVal}%`,
  };
}

